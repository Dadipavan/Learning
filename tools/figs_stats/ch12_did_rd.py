import numpy as np, matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 11, "axes.spines.top": False, "axes.spines.right": False})
B, O, T, Rd, P = "#2b4fd6", "#b84a22", "#357a70", "#aa2d26", "#6a2fd0"
rng = np.random.default_rng(4)
fig, ax = plt.subplots(1, 2, figsize=(9.5, 4.2))
m = np.arange(-6, 6)
ctrl = 400 - 2.5 * m + rng.normal(0, 3, 12)
trt = ctrl + 20 + rng.normal(0, 3, 12) - 60 * (m >= 0)
ax[0].plot(m, ctrl, color=B, marker="o", label="control")
ax[0].plot(m, trt, color=O, marker="o", label="treated")
ax[0].plot(m[m >= -1], (ctrl + 20)[m >= -1], color=O, ls="--", label="treated, if it had followed control")
ax[0].axvline(-0.5, color="k", lw=1); ax[0].text(-0.4, 438, "launch", fontsize=9)
ax[0].set_xlabel("months relative to launch"); ax[0].set_ylabel("delivery time (min)")
ax[0].set_title("Difference-in-differences: parallel before, apart after"); ax[0].legend(frameon=False, fontsize=8)
rng = np.random.default_rng(8)
score = rng.uniform(0, 100, 800); yv = 30 + 0.4 * score + 5.0 * (score >= 50) + rng.normal(0, 6, 800)
ax[1].scatter(score, yv, s=6, alpha=.35, color="#888888")
for lo, hi, c in ((0, 50, B), (50, 100, O)):
    mk = (score >= lo) & (score < hi); co = np.polyfit(score[mk], yv[mk], 1)
    xs = np.linspace(lo, hi, 2); ax[1].plot(xs, np.polyval(co, xs), color=c, lw=3)
ax[1].axvline(50, color="k", ls="--", lw=1)
ax[1].set_xlabel("score (running variable)"); ax[1].set_ylabel("outcome"); ax[1].set_title("Regression discontinuity: jump at the cutoff")
plt.tight_layout(); plt.savefig("ch12_did_rd.png", dpi=110)
