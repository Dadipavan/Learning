import numpy as np, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
# loss landscape of L(w,b) for data x=(1,2,3), y=(2,4,5)
x = np.array([1., 2., 3.]); y = np.array([2., 4., 5.])
w = np.linspace(-0.5, 3.5, 120); b = np.linspace(-2.5, 3.5, 120)
W, B = np.meshgrid(w, b)
L = sum((W * xi + B - yi) ** 2 for xi, yi in zip(x, y))
fig = plt.figure(figsize=(9, 4.2))
ax = fig.add_subplot(1, 2, 1, projection="3d")
ax.plot_surface(W, B, L, cmap="viridis", alpha=0.9, linewidth=0)
ax.set_xlabel("w (slope)"); ax.set_ylabel("b (intercept)"); ax.set_zlabel("L(w, b)")
ax.set_title("Surface: height = loss", fontsize=10); ax.view_init(28, -60)
ax2 = fig.add_subplot(1, 2, 2)
cs = ax2.contour(W, B, L, levels=[0.5, 2, 5, 10, 20, 40, 80], colors="#2b4fd6")
ax2.clabel(cs, fontsize=8)
ax2.plot([1.5], [2/3], "o", color="#b84a22", ms=8, label="minimum (1.5, 0.667)")
ax2.set_xlabel("w (slope)"); ax2.set_ylabel("b (intercept)")
ax2.set_title("Contours: each curve is one loss value", fontsize=10); ax2.legend(fontsize=8)
fig.tight_layout(); fig.savefig("ch12_surface.png", dpi=110)
